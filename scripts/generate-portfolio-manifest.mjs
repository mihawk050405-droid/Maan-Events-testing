// Scans public/portfolio and writes content/portfolio-manifest.ts.
//
// Photos are dropped in as public/portfolio/<category>/<slug>/NN.<ext>, and the
// extension is whatever the source file happened to be — a single project mixes
// .jpg and .webp freely. Deriving the file list from disk keeps the rendered
// paths honest instead of assuming one extension per project.

import { readdirSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const portfolioDir = join(root, "public", "portfolio");
const outFile = join(root, "content", "portfolio-manifest.ts");

const IMAGE_EXT = /\.(jpe?g|png|webp|avif)$/i;

const dirsIn = (path) =>
  readdirSync(path, { withFileTypes: true })
    .filter((e) => e.isDirectory())
    .map((e) => e.name)
    .sort();

const manifest = {};

for (const category of dirsIn(portfolioDir)) {
  for (const slug of dirsIn(join(portfolioDir, category))) {
    const files = readdirSync(join(portfolioDir, category, slug))
      .filter((f) => IMAGE_EXT.test(f))
      // Order by the numeric prefix so 02 precedes 10, regardless of extension.
      .sort((a, b) => (parseInt(a, 10) || 0) - (parseInt(b, 10) || 0) || a.localeCompare(b));

    if (files.length) manifest[`${category}/${slug}`] = files;
  }
}

const body = Object.entries(manifest)
  .map(([key, files]) => `  "${key}": [${files.map((f) => `"${f}"`).join(", ")}],`)
  .join("\n");

writeFileSync(
  outFile,
  `// AUTO-GENERATED by scripts/generate-portfolio-manifest.mjs — do not edit by hand.
// Regenerate with \`npm run manifest\` (runs automatically on dev and build).

export const portfolioManifest: Record<string, string[]> = {
${body}
};
`,
);

const total = Object.values(manifest).reduce((n, f) => n + f.length, 0);
console.log(
  `portfolio manifest: ${Object.keys(manifest).length} projects, ${total} images -> content/portfolio-manifest.ts`,
);
